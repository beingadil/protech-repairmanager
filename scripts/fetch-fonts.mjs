/**
 * Self-hosts the app's Google Fonts so the built app never contacts Google.
 * Downloads the css2 stylesheet (as Chrome would receive it — woff2 + subsets),
 * saves each font file to public/fonts/ and emits public/fonts/fonts.css with
 * rewritten local URLs. Run: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public', 'fonts');

const FAMILIES = [
  'family=Outfit:wght@400..800',
  'family=Plus+Jakarta+Sans:ital,wght@0,400..800;1,400..800'
];

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

async function fetchCss() {
  const url = `https://fonts.googleapis.com/css2?${FAMILIES.join('&')}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Google Fonts css2 request failed: ${res.status}`);
  return res.text();
}

/** Extracts (font-family, url, weight, style, unicode-range) per @font-face. */
function parseFaceBlocks(css) {
  const blocks = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map((m) => m[1]);
  return blocks.map((block) => {
    const get = (prop) => {
      const m = block.match(new RegExp(`${prop}\\s*:\\s*([^;]+);`));
      return m ? m[1].trim() : '';
    };
    const urlMatch = block.match(/url\(([^)]+)\)/);
    return {
      family: get('font-family').replace(/['"]/g, ''),
      url: urlMatch ? urlMatch[1].replace(/['"]/g, '') : '',
      weight: get('font-weight'),
      style: get('font-style') || 'normal',
      unicodeRange: get('unicode-range')
    };
  });
}

function slugify(family) {
  return family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Font download failed (${res.status}): ${url}`);
  await writeFile(dest, Buffer.from(await res.arrayBuffer()));
}

async function main() {
  await mkdir(outDir, { recursive: true });
  const css = await fetchCss();
  const faces = parseFaceBlocks(css);
  if (faces.length === 0) throw new Error('No @font-face blocks parsed — UA may be blocked.');

  const rewritten = [];
  const seenUrls = new Set();
  const urlIndex = new Map();
  for (const face of faces) {
    if (!face.url) continue;
    if (!seenUrls.has(face.url)) {
      seenUrls.add(face.url);
      urlIndex.set(face.url, urlIndex.size + 1);
    }
    const ext = face.url.includes('.woff2') ? 'woff2' : 'woff';
    const weightSlug = face.weight.replace(/\s+/g, '-');
    const base = `${slugify(face.family)}-${weightSlug}-${face.style.replace(/\s+/g, '')}-${urlIndex.get(face.url)}.${ext}`;
    const file = path.join(outDir, base);
    await download(face.url, file);
    const src = `url('/fonts/${base}') format('${ext}')`;
    rewritten.push(`@font-face {
  font-family: '${face.family}';
  font-style: ${face.style};
  font-weight: ${face.weight};
  font-display: swap;
  src: ${src};
  unicode-range: ${face.unicodeRange};
}`);
  }

  const cssOut = `/* Generated by scripts/fetch-fonts.mjs — self-hosted, do not edit by hand */\n${rewritten.join('\n')}\n`;
  await writeFile(path.join(outDir, 'fonts.css'), cssOut);
  console.log(`Wrote ${rewritten.length} @font-face rules, ${faces.length} faces to ${outDir}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
